import os
from PIL import Image

class 카카오톡_이미지_분할기:
    """
    제공해주신 1254x1254 크기의 카카오톡 아기 이모티콘 시트 이미지를 
    정확히 4x4 그리드로 계산하여 16개의 독립된 개별 이미지 파일로 분할해주는 클래스입니다.
    """
    def __init__(self, 원본_경로: str, 저장_디렉토리: str):
        self.원본_경로 = 원본_경로
        self.저장_디렉토리 = 저장_디렉토리

    def 분할_및_저장(self) -> None:
        if not os.path.exists(self.저장_디렉토리):
            os.makedirs(self.저장_디렉토리)
            print(f"디렉토리 생성됨: {self.저장_디렉토리}")

        # 이미지 로드
        원래_이미지 = Image.open(self.원본_경로)
        가로_크기, 세로_크기 = 원래_이미지.size
        
        # 4x4 분할을 위한 정밀 좌표 계산 (1254 / 4 = 313.5 px)
        이모티콘_이름들 = [
            "01_안녕", "02_방긋", "03_최고야", "04_졸려요",
            "05_어머", "06_삐짐", "07_신나요", "08_뭐야",
            "09_냠냠", "10_사랑해", "11_푹잘게요", "12_목욕끝",
            "13_맛있어요", "14_짝짝짝", "15_쪽", "16_잘자요"
        ]

        인덱스 = 0
        for 행 in range(4):
            for 열 in range(4):
                # 정밀한 좌/우/상/하 정수 좌표 계산
                좌측 = int(round(열 * (가로_크기 / 4.0)))
                상단 = int(round(행 * (세로_크기 / 4.0)))
                우측 = int(round((열 + 1) * (가로_크기 / 4.0)))
                하단 = int(round((행 + 1) * (세로_크기 / 4.0)))

                # 이미지 크롭
                크롭된_이미지 = 원래_이미지.crop((좌측, 상단, 우측, 하단))
                
                # 파일 저장명 설정
                파일_이름 = f"{이모티콘_이름들[인덱스]}.png"
                저장_경로 = os.path.join(self.저장_디렉토리, 파일_이름)
                
                # 저장
                크롭된_이미지.save(저장_경로, "PNG")
                print(f"저장 완료: {저장_경로}")
                인덱스 += 1

def 실행_분할():
    입력_이미지 = "KakaoTalk_20260517_120010800.png"
    출력_폴더 = "KakaoTalk_emoticons_individual"
    
    분할기_인스턴스 = 카카오톡_이미지_분할기(입력_이미지, 출력_폴더)
    분할기_인스턴스.분할_및_저장()

if __name__ == "__main__":
    실행_분할()
