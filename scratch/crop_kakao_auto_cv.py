import os
from PIL import Image, ImageDraw

class 자동_검출_이모티콘_크롭기:
    """
    이모티콘 시트 내 각 셀의 실제 콘텐츠 영역(비흰색 픽셀)을 자동으로 검출하여,
    인접한 이미지 간의 상하좌우 번짐(Bleed)을 100% 방지하고 정밀하게 크롭해주는 클래스입니다.
    """
    def __init__(self, 원본_경로: str, 저장_디렉토리: str, 시작_번호: int, 이름_목록: list):
        self.원본_경로 = 원본_경로
        self.저장_디렉토리 = 저장_디렉토리
        self.시작_번호 = 시작_번호
        self.이름_목록 = 이름_목록

    def 배경_투명화(self, 단일_이미지: Image.Image) -> Image.Image:
        변환된_이미지 = 단일_이미지.convert("RGBA")
        가로, 세로 = 변환된_이미지.size
        투명_색상 = (255, 255, 255, 0)
        
        # 4개 모서리에서 플러드 필 채우기
        시작_포인트들 = [(0, 0), (가로 - 1, 0), (0, 세로 - 1), (가로 - 1, 세로 - 1)]
        for 포인트 in 시작_포인트들:
            ImageDraw.floodfill(변환된_이미지, 포인트, 투명_색상, thresh=30)
            
        return 변환된_이미지

    def 분할_및_변환(self) -> None:
        if not os.path.exists(self.저장_디렉토리):
            os.makedirs(self.저장_디렉토리)

        원래_이미지 = Image.open(self.원본_경로)
        가로_전체, 세로_전체 = 원래_이미지.size
        픽셀_데이터 = 원래_이미지.convert("RGB")

        # 4x4 등분 기준 크기
        단일_가로 = 가로_전체 // 4
        단일_세로 = 세로_전체 // 4

        인덱스 = 0
        for 행 in range(4):
            for 열 in range(4):
                # 1. 셀 검색 영역 지정 (인접 셀 간섭 방지를 위해 가장자리 15px 안쪽에서 검색)
                검색_좌 = 열 * 단일_가로 + 15
                검색_우 = (열 + 1) * 단일_가로 - 15
                검색_상 = 행 * 단일_세로 + 15
                검색_하 = (행 + 1) * 단일_세로 - 15

                # 2. 비흰색(실제 이모티콘 픽셀) 좌표 탐색
                x_좌표들 = []
                y_좌표들 = []
                
                for y in range(검색_상, 검색_하):
                    for x in range(검색_좌, 검색_우):
                        r, g, b = 픽셀_데이터.getpixel((x, y))
                        # 흰색 배경(250 이상)이 아닌 실제 그림 픽셀 탐색
                        if r < 248 or g < 248 or b < 248:
                            x_좌표들.append(x)
                            y_좌표들.append(y)

                # 3. 바운딩 박스 결정 및 크롭 영역 산정 (안전 마진 12px 추가)
                if x_좌표들 and y_좌표들:
                    최소_x = min(x_좌표들)
                    최대_x = max(x_좌표들)
                    최소_y = min(y_좌표들)
                    최대_y = max(y_좌표들)

                    크롭_좌 = max(열 * 단일_가로, 최소_x - 12)
                    크롭_우 = min((열 + 1) * 단일_가로, 최대_x + 12)
                    크롭_상 = max(행 * 단일_세로, 최소_y - 12)
                    크롭_하 = min((행 + 1) * 단일_세로, 최대_y + 12)
                else:
                    # 감지 실패 시 기본값 크롭
                    크롭_좌 = 열 * 단일_가로 + 10
                    크롭_우 = (열 + 1) * 단일_가로 - 10
                    크롭_상 = 행 * 단일_세로 + 10
                    크롭_하 = (행 + 1) * 단일_세로 - 10

                # 4. 크롭 및 가공
                크롭된_이미지 = 원래_이미지.crop((크롭_좌, 크롭_상, 크롭_우, 크롭_하))
                투명_이미지 = self.배경_투명화(크롭된_이미지)
                
                # 360x360 카카오 공식 크기로 변환
                최종_이미지 = 투명_이미지.resize((360, 360), Image.Resampling.LANCZOS)
                
                # 파일 저장
                파일_이름 = f"{self.이름_목록[인덱스]}.png"
                저장_경로 = os.path.join(self.저장_디렉토리, 파일_이름)
                최종_이미지.save(저장_경로, "PNG")
                
                print(f"[{self.시작_번호 + 인덱스:02d}번] 정밀 자동 크롭 완료: {저장_경로} (영역: {크롭_좌},{크롭_상} ~ {크롭_우},{크롭_하})")
                인덱스 += 1

