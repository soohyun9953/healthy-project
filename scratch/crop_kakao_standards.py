import os
from PIL import Image, ImageDraw

class 카카오_규격_이모티콘_변환기:
    """
    4x4 이모티콘 시트 이미지를 카카오톡 공식 제안 규격(360x360 px, 투명 배경 PNG)에 맞춰
    분할 및 가공해주는 전문 변환기 클래스입니다.
    """
    def __init__(self, 원본_경로: str, 저장_디렉토리: str):
        self.원본_경로 = 원본_경로
        self.저장_디렉토리 = 저장_디렉토리

    def 배경_투명화(self, 단일_이미지: Image.Image) -> Image.Image:
        변환된_이미지 = 단일_이미지.convert("RGBA")
        가로, 세로 = 변환된_이미지.size
        투명_색상 = (255, 255, 255, 0)
        
        # 4개 모서리에서 플러드 필 시작
        시작_포인트들 = [(0, 0), (가로 - 1, 0), (0, 세로 - 1), (가로 - 1, 세로 - 1)]
        for 포인트 in 시작_포인트들:
            ImageDraw.floodfill(변환된_이미지, 포인트, 투명_색상, thresh=30)
            
        return 변환된_이미지

    def 분할_및_변환(self) -> None:
        if not os.path.exists(self.저장_디렉토리):
            os.makedirs(self.저장_디렉토리)

        원래_이미지 = Image.open(self.원본_경로)
        
        # 인접 셀 간의 간섭(번짐)을 완전히 방지하기 위한 정밀 좌표 매핑 (안전 마진 8~10px 부여)
        좌측_좌표들 = [0, 258, 516, 774]
        우측_좌표들 = [250, 508, 766, 1024]
        상단_좌표들 = [0, 260, 516, 772]
        하단_좌표들 = [250, 506, 762, 1018]

        # 실제 1차 이미지 내 텍스트와 100% 일치하도록 파일명 수정
        이모티콘_이름들 = [
            "01_안녕", "02_웅", "03_헤헷", "04_졸려요",
            "05_힝ㅠㅠ", "06_우와", "07_좋아요", "08_쳇",
            "09_뿌잉뿌잉", "10_크앙", "11_냠냠", "12_멍",
            "13_반짝", "14_부끄부끄", "15_부탁해", "16_화남"
        ]

        인덱스 = 0
        for 행 in range(4):
            for 열 in range(4):
                좌측 = 좌측_좌표들[열]
                상단 = 상단_좌표들[행]
                우측 = 우측_좌표들[열]
                하단 = 하단_좌표들[행]

                크롭된_이미지 = 원래_이미지.crop((좌측, 상단, 우측, 하단))
                투명_이미지 = self.배경_투명화(크롭된_이미지)
                최종_이미지 = 투명_이미지.resize((360, 360), Image.Resampling.LANCZOS)
                
                파일_이름 = f"{이모티콘_이름들[인덱스]}.png"
                저장_경로 = os.path.join(self.저장_디렉토리, 파일_이름)
                
                최종_이미지.save(저장_경로, "PNG")
                print(f"카카오 1차 정밀 변환 완료: {저장_경로}")
                인덱스 += 1

def 실행_변환():
    입력_이미지 = "baby_standard_emoticons.png"
    출력_폴더 = "baby_kakao_official"
    
    변환기_인스턴스 = 카카오_규격_이모티콘_변환기(입력_이미지, 출력_폴더)
    변환기_인스턴스.분할_및_변환()

if __name__ == "__main__":
    실행_변환()
