import os
from PIL import Image

class 이미지_분할기:
    """
    4x4 이모티콘 그리드 시트 이미지를 각각의 독립된 개별 이미지 파일로 분할해주는 클래스입니다.
    """
    def __init__(self, 원본_경로: str, 저장_디렉토리: str):
        self.원본_경로 = 원본_경로
        self.저장_디렉토리 = 저장_디렉토리

    def 분할_및_저장(self) -> None:
        if not os.path.exists(self.저장_디렉토리):
            os.makedirs(self.저장_디렉토리)
            print(f"디렉토리 생성됨: {self.저장_디렉토리}")

        # 이미지 로드
        원래_이미지 = Image.open(self.원본_경로)
        가로_크기, 세로_크기 = 원래_이미지.size
        
        # 4x4 분할을 위한 단일 이모티콘 크기 계산
        단일_가로 = 가로_크기 // 4
        단일_세로 = 세로_크기 // 4

        이모티콘_이름들 = [
            "01_안녕", "02_쿨쿨", "03_흑흑", "04_냠냠",
            "05_헤헤", "06_깜짝", "07_아자", "08_하트",
            "09_웅", "10_휴우", "11_뿡", "12_사랑",
            "13_총총", "14_맘마", "15_고마워", "16_찡긋"
        ]

        인덱스 = 0
        for 행 in range(4):
            for 열 in range(4):
                # 자를 영역 정의 (좌, 상, 우, 하)
                좌측 = 열 * 단일_가로
                상단 = 행 * 단일_세로
                우측 = 좌측 + 단일_가로
                하단 = 상단 + 단일_세로

                # 이미지 크롭
                크롭된_이미지 = 원래_이미지.crop((좌측, 상단, 우측, 하단))
                
                # 파일 저장명 설정
                파일_이름 = f"{이모티콘_이름들[인덱스]}.png"
                저장_경로 = os.path.join(self.저장_디렉토리, 파일_이름)
                
                # 저장
                크롭된_이미지.save(저장_경로, "PNG")
                print(f"저장 완료: {저장_경로}")
                인덱스 += 1

def 실행_분할():
    입력_이미지 = "baby_emoticon_sheet.png"
    출력_폴더 = "baby_emoticons_individual"
    
    분할기_인스턴스 = 이미지_분할기(입력_이미지, 출력_폴더)
    분할기_인스턴스.분할_및_저장()

if __name__ == "__main__":
    실행_분할()
